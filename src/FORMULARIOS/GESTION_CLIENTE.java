    private void btn_registrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_registrarActionPerformed
        String dni, nom, ape, sexo = "", cel;

    dni = txt_dni.getText().trim();
    nom = txt_nombres.getText().trim();
    ape = txt_apellidos.getText().trim();
    cel = txt_celular.getText().trim();

    if (rdo_masculino.isSelected()) {
        sexo = "MASCULINO";
    } else if (rdo_femenino.isSelected()) {
        sexo = "FEMENINO";
    } else {
        JOptionPane.showMessageDialog(this, "⚠️ Por favor seleccione el sexo.");
        return;
    }

    if (dni.isEmpty() || nom.isEmpty() || ape.isEmpty() || cel.isEmpty()) {
        JOptionPane.showMessageDialog(this, "⚠️ Complete todos los campos antes de guardar.");
        return;
    }

    try {
        ADMINISTRAR_ALTA_CLIENTE reg = new ADMINISTRAR_ALTA_CLIENTE();
        reg.GUARDAR(dni, nom, ape, sexo, cel);

        JOptionPane.showMessageDialog(this, "✅ Cliente registrado correctamente.");
        new FORMULARIOS.REGISTRO_VENTAS().MostrarClientes();
        this.setVisible(false);

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "❌ Error al registrar: " + e.getMessage());
    }
    }//GEN-LAST:event_btn_registrarActionPerformed

