    private void aplicarSegunRol() {

    String rol = CLASES.SesionUsuario.ROL;

    if (rol == null) return;

    if (rol.equalsIgnoreCase("VENTAS")) {

        // ❌ Vendedor NO puede ver usuarios
        btn_usuarios.setEnabled(false);
        //jp_usuario.setVisible(false);

        // ❌ No puede ver reportes
        btn_reportes.setEnabled(false);
        //jp_reportes.setVisible(false);

        // ❌ No puede entrar a productos
        btn_productos.setEnabled(false);
        //jp_logistica.setVisible(false);

        // ✔ Solo ventas habilitado
        btn_venta.setEnabled(true);

    } else if (rol.equalsIgnoreCase("ADMINISTRADOR")) {

        // ✔ Acceso total
        btn_usuarios.setEnabled(true);
        jp_usuario.setVisible(true);

        btn_reportes.setEnabled(true);
        jp_reportes.setVisible(true);

        btn_productos.setEnabled(true);
        jp_logistica.setVisible(true);

        btn_venta.setEnabled(true);
    }
}

